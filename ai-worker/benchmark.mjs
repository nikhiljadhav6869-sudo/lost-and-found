import fs from 'node:fs';
import {embed} from './models.mjs';
import assert from 'node:assert/strict';
const cosine=(a,b)=>a.reduce((s,x,i)=>s+x*b[i],0);
const started=performance.now();
const photo=fs.readFileSync(new URL('../tests/fixtures/sample.png',import.meta.url));
const first=await embed('Black wireless earbuds in a small charging case.',[photo]);
const coldMs=performance.now()-started;
const warm=performance.now();
const paraphrase=await embed('Dark Bluetooth earphones with their box.');
const unrelated=await embed('A red wool winter scarf with white stripes.');
const repeated=await embed('Black wireless earbuds in a small charging case.',[photo]);
const related=cosine(first.textVector,paraphrase.textVector),negative=cosine(first.textVector,unrelated.textVector);
assert.equal(first.textVector.length,384);assert.equal(first.imageVector.length,512);
assert.ok(related>negative,'Paraphrase should rank above an unrelated item');
assert.ok(cosine(first.imageVector,repeated.imageVector)>0.999,'Repeated image should give the same embedding');
const result={date:new Date().toISOString(),models:'Pinned MiniLM + CLIP q8',firstInferenceWithCachedDownloadsMs:Math.round(coldMs),threeWarmCallsMs:Math.round(performance.now()-warm),rssMB:Math.round(process.memoryUsage().rss/1048576),paraphraseCosine:related,unrelatedCosine:negative,identicalPhotoCosine:cosine(first.imageVector,repeated.imageVector),limitation:'Synthetic smoke benchmark, not an accuracy study or real-world object identification validation.'};
fs.mkdirSync(new URL('../.sites-runtime/',import.meta.url),{recursive:true});
fs.writeFileSync(new URL('../.sites-runtime/ai-benchmark.json',import.meta.url),JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
